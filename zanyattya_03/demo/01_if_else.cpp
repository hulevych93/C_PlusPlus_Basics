/*
    Заняття 3 · Демонстрація 1. if і else.
*/

#include <iostream>

int main() {

    // =====================================================================
    // КРОК 1. Одна умова
    // =====================================================================
    // Ввести бал. Якщо він 60 або більше — вивести Passed.
    //
    // Очікуваний вивід:
    //   75  ->  Passed
    //   40  ->  нічого

    int score = 0;
    std::cin >> score;

    if (score >= 60) {
        std::cout << "Passed\n";
    }

    // =====================================================================
    // КРОК 2. Дві гілки
    // =====================================================================
    // Додати гілку else: якщо бал менший за 60 — вивести Failed.
    //
    // Очікуваний вивід:
    //   75  ->  Passed
    //   40  ->  Failed

    if (score >= 60) {
        std::cout << "Passed\n";
    } else {
        std::cout << "Failed\n";
    }

    // =====================================================================
    // КРОК 3. Умова як значення
    // =====================================================================
    // Зберегти результат порівняння у змінну типу bool і вивести її.
    //
    // Очікуваний вивід:
    //   75  ->  1
    //   40  ->  0

    bool passed = score >= 60;
    std::cout << passed << "\n";

    return 0;
}
