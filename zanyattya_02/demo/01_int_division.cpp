#include <iostream>

int main() {

    // =====================================================================
    // КРОК 1. Тижні в році
    // =====================================================================
    // У році 365 днів. Вивести кількість повних тижнів і днів, що лишились.
    //
    // Очікуваний вивід:
    //   52 1

    int days = 365;
    std::cout << days / 7 << " " << days % 7 << "\n";

    // =====================================================================
    // КРОК 2. Остача
    // =====================================================================
    // Ввести ціле число й вивести остачу від його ділення на 2.
    //
    // Очікуваний вивід:
    //   7  ->  1
    //   8  ->  0

    int n = 0;
    std::cin >> n;
    std::cout << n % 2 << "\n";

    // =====================================================================
    // КРОК 3. Хвилини й секунди
    // =====================================================================
    // Ввести кількість секунд. Вивести повні хвилини й секунди понад них.
    //
    // Очікуваний вивід:
    //   1000  ->  16 40
    //   59    ->  0 59

    int total = 0;
    std::cin >> total;
    std::cout << total / 60 << " " << total % 60 << "\n";

    return 0;
}
