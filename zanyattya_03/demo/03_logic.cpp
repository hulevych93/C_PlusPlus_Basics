/*
    Заняття 3 · Демонстрація 3. Логічні операції.

    Допуск датчика: від -40 до 60 °C включно.
*/

#include <iostream>

int main() {

    // =====================================================================
    // КРОК 1. І — обидві умови разом
    // =====================================================================
    // Ввести температуру. Якщо вона в межах допуску — вивести OK,
    // інакше — OUT.
    //
    // Очікуваний вивід:
    //   20   ->  OK
    //   70   ->  OUT
    //   -40  ->  OK

    double t = 0;
    std::cin >> t;

    if (t >= -40 && t <= 60) {
        std::cout << "OK\n";
    } else {
        std::cout << "OUT\n";
    }

    // =====================================================================
    // КРОК 2. АБО — достатньо однієї
    // =====================================================================
    // Та сама перевірка, записана через вихід за межі.
    //
    // Очікуваний вивід:
    //   20   ->  OK
    //   70   ->  OUT

    if (t < -40 || t > 60) {
        std::cout << "OUT\n";
    } else {
        std::cout << "OK\n";
    }

    // =====================================================================
    // КРОК 3. НЕ — заперечення
    // =====================================================================
    // Зберегти результат перевірки у змінну bool і вивести її заперечення.
    //
    // Очікуваний вивід:
    //   20  ->  0
    //   70  ->  1

    bool ok = t >= -40 && t <= 60;
    std::cout << !ok << "\n";

    return 0;
}
