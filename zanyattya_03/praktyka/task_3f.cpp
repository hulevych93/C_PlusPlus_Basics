/*
    Заняття 3 · Задача 3f. Знайти помилку.

    Програма нижче має виводити zero, якщо введене число дорівнює нулю,
    і not zero в усіх інших випадках. Вона компілюється, але для будь-якого
    числа виводить not zero. Знайти й виправити помилку.

    Перевірка після виправлення:
      0   ->  zero
      5   ->  not zero
      -3  ->  not zero
*/

#include <iostream>

int main() {

    int n = 0;
    std::cin >> n;

    if (n = 0) {
        std::cout << "zero\n";
    } else {
        std::cout << "not zero\n";
    }

    return 0;
}
