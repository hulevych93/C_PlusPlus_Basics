#include <iostream>

int main() {

    // =====================================================================
    // КРОК 1. Три варіанти
    // =====================================================================
    // Ввести бал. Від 90 — excellent, від 60 — pass, менше — fail.
    //
    // Очікуваний вивід:
    //   95  ->  excellent
    //   75  ->  pass
    //   40  ->  fail

    int score = 0;
    std::cin >> score;

    if (score >= 90) {
        std::cout << "excellent\n";
    } else if (score >= 60) {
        std::cout << "pass\n";
    } else {
        std::cout << "fail\n";
    }

    // =====================================================================
    // КРОК 2. Порядок гілок
    // =====================================================================
    // Ті самі умови в оберненому порядку. Комп'ютер зупиняється
    // на першій правдивій умові, тому для 95 тепер виходить pass.
    //
    // Очікуваний вивід:
    //   95  ->  pass

    if (score >= 60) {
        std::cout << "pass\n";
    } else if (score >= 90) {
        std::cout << "excellent\n";
    } else {
        std::cout << "fail\n";
    }

    return 0;
}
