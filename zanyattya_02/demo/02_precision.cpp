#include <iostream>
#include <iomanip>
#include <cmath>

int main() {

    // =====================================================================
    // КРОК 1. Піца: ціле ділення
    // =====================================================================
    // Поділити 8 шматків на 3 осіб і записати результат у змінну double.
    //
    // Очікуваний вивід:
    //   2

    double share = 8 / 3;
    std::cout << share << "\n";

    // =====================================================================
    // КРОК 2. Піца: дробове ділення
    // =====================================================================
    // Змінити вираз так, щоб результат мав дробову частину.
    //
    // Очікуваний вивід:
    //   2.66667

    share = 8.0 / 3;
    std::cout << share << "\n";

    // =====================================================================
    // КРОК 3. Перевірка 0.1 + 0.2 == 0.3
    // =====================================================================
    // Вивести результат порівняння. 1 — правда, 0 — неправда.
    //
    // Очікуваний вивід:
    //   0

    std::cout << (0.1 + 0.2 == 0.3) << "\n";

    // =====================================================================
    // КРОК 4. Сімнадцять значущих цифр
    // =====================================================================
    // Вивести 0.1 + 0.2 із 17 значущими цифрами.
    //
    // Очікуваний вивід:
    //   0.30000000000000004

    std::cout << std::setprecision(17) << 0.1 + 0.2 << "\n";
    std::cout << std::setprecision(6);

    // =====================================================================
    // КРОК 5. Обрізання й округлення
    // =====================================================================
    // Перетворити 2.99 на ціле через static_cast<int> і через std::lround.
    //
    // Очікуваний вивід:
    //   2
    //   3

    std::cout << static_cast<int>(2.99) << "\n";
    std::cout << std::lround(2.99) << "\n";

    // =====================================================================
    // КРОК 6. Загублена копійка
    // =====================================================================
    // Те саме для 0.29 * 100.
    //
    // Очікуваний вивід:
    //   28
    //   29

    std::cout << static_cast<int>(0.29 * 100) << "\n";
    std::cout << std::lround(0.29 * 100) << "\n";

    return 0;
}
